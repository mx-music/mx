  # The notes of a bar as Joplin wrote them, as {staff, sixteenth, notes, sixteenths held}, bar 0
  # being the pickup, the strains played as the score repeats them: A A B B A C C D D.
  def written(bar) when bar in 0..144 do
    {_, right, left} = List.keyfind(score(), engraved(bar), 0)

    for {staff, chords} <- [right: right, left: left],
        {sixteenth, notes, length} <- chords,
        do: {staff, sixteenth, notes, length}
  end

  # The engraved bar that a played bar repeats.
  defp engraved(bar) when bar in 65..79, do: bar - 64
  defp engraved(80), do: 32

  defp engraved(bar) do
    repeated = bar in 17..31 or bar in 49..63 or bar in 97..111 or bar in 129..143
    if repeated, do: bar - 16, else: bar
  end

