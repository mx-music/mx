  # The pedal changes on each bar and whenever the left hand reaches lower than all it played
  # since the last change.
  defp pedals(lower) do
    lower
    |> Enum.flat_map(fn {beat, notes, _length} -> Enum.map(notes, &{beat, &1}) end)
    |> Enum.sort()
    |> Enum.reduce({[0], 128}, fn {beat, note}, {changes, low} ->
      if note < low and beat > 0, do: {[beat | changes], note}, else: {changes, min(note, low)}
    end)
    |> elem(0)
    |> Enum.uniq()
    |> Enum.reverse()
  end

  # The value at a place of a curve given as keys, straight between them.
  defp along(keys, at) do
    span =
      keys
      |> Enum.chunk_every(2, 1, :discard)
      |> Enum.find(fn [{from, _}, {to, _}] -> at >= from and at < to end)

    case span do
      [{from, a}, {to, b}] -> a + (b - a) * (at - from) / (to - from)
      nil -> keys |> List.last() |> elem(1)
    end
  end

