defmodule ClairDeLune do
  # Every note of a bar as {beat, note, velocity, sustain}: the right hand's top note sings over
  # the rest, the bass under each pedal sounds full, and the inner notes stay back a little behind
  # the melody.
  def strokes(bar) do
    {^bar, upper, lower} = List.keyfind(score(), bar, 0)
    changes = pedals(lower)

    notes =
      for {staff, chords} <- [upper: upper, lower: lower],
          {beat, notes, length} <- chords,
          note <- notes,
          do: {staff, beat, note, length}

    tops =
      notes
      |> Enum.filter(&(elem(&1, 0) == :upper))
      |> Enum.group_by(&elem(&1, 1), &elem(&1, 2))
      |> Map.new(fn {beat, ns} -> {beat, Enum.max(ns)} end)

    basses =
      notes
      |> Enum.filter(&(elem(&1, 0) == :lower and elem(&1, 1) in changes))
      |> Enum.group_by(&elem(&1, 1), &elem(&1, 2))
      |> Map.new(fn {beat, ns} -> {beat, Enum.min(ns)} end)

    for {staff, beat, note, length} <- notes do
      base = along(loudness(), bar + beat / 9)
      pedal = Enum.find(changes, 9, &(&1 > beat))

      again =
        notes
        |> Enum.filter(&(elem(&1, 2) == note and elem(&1, 1) > beat))
        |> Enum.map(&elem(&1, 1))
        |> Enum.min(fn -> 99 end)

      held = min(max(length, pedal - beat), again - beat)

      {touch, lag} = touch(staff, note, tops[beat], basses[beat])
      start = warp(bar, beat + lag)

      {Float.round(start, 3), note, Float.round(min(base * touch, 1.0), 2),
       Float.round(warp(bar, beat + held) - start, 2)}
    end
    |> Enum.sort()
  end

  # The beat at which a point of a bar sounds, past its end at the pace of its last eighth.
  def warp(bar, eighth) do
    lengths = eighths(bar)
    whole = min(trunc(eighth), 8)

    lengths
    |> Enum.take(whole)
    |> Enum.sum()
    |> Kernel.+((eighth - whole) * Enum.at(lengths, whole))
  end

