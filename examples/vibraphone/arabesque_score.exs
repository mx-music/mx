  # 3 to 18 again, but for one bass note of bars 77 and 79.
  defp engraved(71), do: 17
  defp engraved(72), do: 18

  defp engraved(bar) do
    repeated = bar in 73..88 and bar not in [77, 79]
    if repeated, do: bar - 70, else: bar
  end

