  # touch, pedal or rubato.
  def written(bar) when bar in 1..106 do
    {_, upper, lower} = List.keyfind(score(), engraved(bar), 0)

    for {staff, chords} <- [upper: upper, lower: lower],
        {twelfth, notes, length} <- chords,
        do: {staff, twelfth, notes, length}
  end

